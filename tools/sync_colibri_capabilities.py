#!/usr/bin/env python3
"""Build-time snapshot of upstream discovery metadata, never execution permission.

The shipped C catalogue has no Python dependency. --check compares all families,
including non-chat engines and families without Edge/Segment implementations.
"""
import argparse
import json
from pathlib import Path
import runpy
import sys


def render(engine):
    families = runpy.run_path(str(engine / 'family_registry.py'))['FAMILIES']
    rows, aliases = [], set()
    for f in sorted(families, key=lambda f: f.id):
        if f.modality not in ('text', 'image', 'decision'):
            raise ValueError(f'new modality requires integration: {f.id}: {f.modality}')
        names = list(f.model_types)
        if not names or aliases.intersection(names):
            raise ValueError(f'empty or ambiguous aliases: {f.id}')
        aliases.update(names)
        caps = f.capabilities
        operations = {'text': ['LMB_OP_CHAT'], 'image': ['LMB_OP_GENERATE_IMAGE'],
                      'decision': ['LMB_OP_DECIDE']}[f.modality].copy()
        for flag, op in [('image', 'LMB_OP_IMAGE_INPUT'), ('audio_payload', 'LMB_OP_AUDIO_INPUT'),
                         ('tools', 'LMB_OP_TOOLS'), ('logprobs_echo', 'LMB_OP_LOGPROBS')]:
            if getattr(caps, flag):
                operations.append(op)
        # Delimiters make aliases exact; no prefix or substring dispatch.
        if any('|' in n or not n.isascii() for n in names):
            raise ValueError(f'unrepresentable alias: {f.id}')
        rows.append('    {%s, %s, %s, %s, %s, %du},' % (
            json.dumps(f.id), json.dumps(f.engine_artifact), json.dumps(f.modality),
            json.dumps('|' + '|'.join(names) + '|'), ' | '.join(operations), f.limits.max_context))
    return ('/* Generated by tools/sync_colibri_capabilities.py. Do not edit.\n'
            ' * Upstream metadata: not proof of a checkpoint, backend or distributed implementation. */\n'
            '#ifndef LMB_COLIBRI_CAPABILITIES_DATA_H\n#define LMB_COLIBRI_CAPABILITIES_DATA_H\n'
            'static const LmbFamilyCapabilities LMB_COLIBRI_CAPABILITIES[] = {\n' +
            '\n'.join(rows) + '\n};\n#endif\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--engine', required=True, type=Path)
    p.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] /
                   'src/planner/lumabri_colibri_capabilities_data.h')
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    expected = render(a.engine)
    if a.check:
        if not a.output.is_file() or a.output.read_text() != expected:
            print('Colibri capability registry changed. Review every new family/operation; '
                  'regenerate metadata and implement its checkpoint/runtime contracts.', file=sys.stderr)
            return 1
    else:
        a.output.write_text(expected)
    return 0


if __name__ == '__main__':
    sys.exit(main())
