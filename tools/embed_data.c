/* Build-time native C utility: ship named data files inside a binary.
 * Usage: embed-data NAME=FILE... > header. Each file becomes a
 * NUL-terminated `static const unsigned char NAME[]`. No Python, runtime
 * filesystem lookup or network is required. */
#include <stdio.h>
#include <string.h>

int main(int argc, char **argv) {
    if (argc<2) return 1;
    puts("/* Generated by tools/embed_data.c; do not edit. */");
    for (int i=1; i<argc; i++) {
        char *file=strchr(argv[i],'=');
        if (!file || file==argv[i] || !file[1]) return 1;
        *file++=0;
        for (const char *p=argv[i]; *p; p++)
            if (!((*p>='a' && *p<='z') || (*p>='0' && *p<='9' && p!=argv[i]) || *p=='_')) return 1;
        FILE *input=fopen(file,"rb"); if (!input) { perror(file); return 1; }
        printf("static const unsigned char %s[]={\n",argv[i]);
        unsigned count=0; int byte;
        while ((byte=fgetc(input))!=EOF) {
            printf("%u,",(unsigned)byte);
            if (++count%24==0) putchar('\n');
        }
        int bad=ferror(input); fclose(input); if (bad || !count) return 1;
        puts("0};");
    }
    return fflush(stdout) || ferror(stdout) ? 1 : 0;
}
