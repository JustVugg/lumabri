#!/usr/bin/env python3
"""Let a Qwen3.6 Segment use the engine's CUDA expert tier.

The pinned engine starts its CUDA tier in main() and its Segment adapter
accepts the CPU only. This edits Lumabri's build copy, never the engine
source: the block main() runs after loading a model becomes a function, and
the Segment adapter calls it for its own layers when the caller allows CUDA.

Nothing here is compiled without -DCOLI_CUDA, so an ordinary build is
unchanged. Every anchor must match exactly once: a different engine revision
fails the build here instead of producing a wrong binary.
"""
import sys


def once(text, old, new):
    if text.count(old) != 1:
        raise SystemExit("prepare_cuda_segment: anchor matched %d times: %r" % (text.count(old), old[:70]))
    return text.replace(old, new)


def function(lines, start):
    first = next(i for i, line in enumerate(lines) if line.startswith(start))
    last = next(i for i in range(first, len(lines)) if lines[i] == "}")
    return "\n".join(lines[first:last + 1]) + "\n"


def main():
    path = sys.argv[1]
    text = open(path, encoding="utf-8").read()
    if "lmb_q36_gpu_start" in text:
        return
    lines = text.split("\n")
    begin = next(i for i, line in enumerate(lines) if "int expert_is_int4 = 1, expert_mixed = 0;" in line)
    end = next(i for i, line in enumerate(lines) if "q36c_start(&m);" in line)
    block = lines[begin:end - 1]
    if block[-1].strip() or block[-2].strip() != "}":
        raise SystemExit("prepare_cuda_segment: the CUDA start block has moved")
    block = "\n".join(block)
    outside = "(l < lmb_gpu_lo || l >= lmb_gpu_hi)"
    # A Segment loads its own layers only. The tier sizes one slot table for
    # the whole model, so the layers held elsewhere borrow a loaded layer's
    # sizes and are then switched off: nothing of theirs is planned or read.
    block = once(block, "const GqExp *x = &m.gqx[l];", "const GqExp *x = &m.gqx[%s ? lmb_gpu_lo : l];" % outside)
    block = once(block, "        atexit(qt_shutdown);",
                 "        atexit(qt_shutdown);\n"
                 "        for (int l = 0; l < m.c.n_layers; l++) if %s qt_layer_off(l);" % outside)
    warm = function(lines, "static void tier_warmstart(")
    warm = once(warm, "        if (q36_dense_l(&m->c, l)) continue;",
                "        if (q36_dense_l(&m->c, l) || %s) continue;" % outside)
    start = ("#ifdef COLI_CUDA\n"
             "/* Lumabri: the standalone engine's CUDA start, for the layers of one Segment.\n"
             " * Generated by tools/prepare_cuda_segment.py from main(). */\n"
             "static int lmb_gpu_lo, lmb_gpu_hi;\n" + function(lines, "static void tier_src(") + warm +
             "static void lmb_q36_gpu_start(Model *lmb_model, int cap) {\n#define m (*lmb_model)\n" + block +
             "\n#undef m\n}\n#define LMB_Q36_SEGMENT_BACKENDS (COLI_SEGMENT_CAP_CPU | COLI_SEGMENT_CAP_CUDA)\n"
             "#else\n#define LMB_Q36_SEGMENT_BACKENDS COLI_SEGMENT_CAP_CPU\n#endif\n")
    opened = next(i for i, line in enumerate(lines) if line.startswith("static int qwen36_segment_engine_open_inner("))
    closed = next(i for i in range(opened, len(lines)) if lines[i] == "}")
    body = "\n".join(lines[opened:closed + 1])
    body = once(body, "        (options->backend_mask & ~COLI_SEGMENT_CAP_CPU))",
                "        (options->backend_mask & ~LMB_Q36_SEGMENT_BACKENDS))")
    # Before the resident preparation: the tier decides how the experts are
    # held in RAM, so it must exist before the first one is loaded.
    body = once(body, "    engine->model.resident_mode = 0;\n",
                "    engine->model.resident_mode = 0;\n"
                "#ifdef COLI_CUDA\n"
                "    if (options->backend_mask & COLI_SEGMENT_CAP_CUDA) {\n"
                "        setenv(\"COLI_CUDA\", \"1\", 1);\n"
                "        lmb_gpu_lo = (int)options->layer_begin; lmb_gpu_hi = (int)options->layer_end;\n"
                "        fprintf(stderr, \"[lumabri-gpu] CUDA requested for layers %d:%d\\n\", lmb_gpu_lo, lmb_gpu_hi);\n"
                "        lmb_q36_gpu_start(&engine->model, cap ? cap : engine->model.c.n_experts);\n"
                "    }\n"
                "#endif\n")
    body = once(body, "                          COLI_SEGMENT_CAP_CPU;\n",
                "                          COLI_SEGMENT_CAP_CPU;\n"
                "#ifdef COLI_CUDA\n"
                "    /* Reported only when the device really holds something. */\n"
                "    if ((options->backend_mask & COLI_SEGMENT_CAP_CUDA) && qt_ready())\n"
                "        capabilities->flags |= COLI_SEGMENT_CAP_CUDA;\n"
                "#endif\n")
    lines[opened:closed + 1] = (start + body).split("\n")
    open(path, "w", encoding="utf-8").write("\n".join(lines))


if __name__ == "__main__":
    main()
